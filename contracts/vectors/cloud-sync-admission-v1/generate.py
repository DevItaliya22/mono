"""Print deterministic admission vectors; no production keys, I/O or services.

Requires Python cryptography for an independent Ed25519 implementation.
The committed JSON is immutable test input, not regenerated by Rust tests.
"""
import base64
import hashlib
import json
import uuid
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat


def encode(value):
    return json.dumps(value, separators=(",", ":"), ensure_ascii=True).encode()


def b64(value):
    return base64.urlsafe_b64encode(value).decode().rstrip("=")


def identifier(byte):
    return str(uuid.UUID(bytes=bytes([byte]) * 16, version=4))


keys = {name: Ed25519PrivateKey.from_private_bytes(bytes([byte]) * 32)
        for name, byte in [("regional", 1), ("previous", 2), ("device", 3), ("worker", 4), ("client_endpoint", 5)]}
public = {name: list(key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw))
          for name, key in keys.items()}


def token(claims, kind, kid="regional", key=None):
    header = {"alg": "EdDSA", "typ": kind, "kid": kid}
    signing = b64(encode(header)) + "." + b64(encode(claims))
    return signing + "." + b64((key or keys[kid]).sign(signing.encode()))


workspace = dict(kind="workspace", workspace_id=identifier(10),
                 incarnation_id=identifier(11), logical_replica_id=identifier(12))
profile = dict(kind="profile", profile_id=identifier(13),
               lineage_id=identifier(14), logical_replica_id=identifier(15))
credential_claims = dict(ver=1, purpose="koru:sync:device:v1", iss="https://us.example.invalid",
    aud="koru-sync", region="US", sub=identifier(16), profile_id=identifier(13),
    device_id=identifier(17), client_endpoint_id=public["client_endpoint"], workspace_id=identifier(10),
    workspace_incarnation_id=identifier(11), workspace_replica_id=identifier(12),
    profile_lineage_id=identifier(14), profile_replica_id=identifier(15),
    authorization_version=21, membership_epoch=22, cloud_access_epoch=23,
    iat=1800000000, exp=1800000600, jti=identifier(18))
credential = token(credential_claims, "koru-sync-credential+jwt")
sessions = []
for dataset in [workspace, profile]:
    # D231 withdrew the signed worker route attestation. What remains is the
    # worker's own assignment rows: never serialized, never signed, never on the
    # wire. They are frozen here so a test can arm the authority a worker reads.
    assignment = dict(dataset=dataset, worker_endpoint_id=public["worker"],
        worker_id=identifier(19), lease_id=identifier(20), lease_epoch=24)
    nonce_c, nonce_w = bytes([30]) * 32, bytes([31]) * 32
    domain = b"koru/cloud-sync/client-finish/v1\0"
    assert len(domain) == 33
    scope = "workspace_id" if dataset["kind"] == "workspace" else "profile_id"
    lineage = "incarnation_id" if dataset["kind"] == "workspace" else "lineage_id"
    transcript = (domain + (1).to_bytes(2, "big") + bytes(public["client_endpoint"])
        + bytes(public["worker"]) + bytes([1 if scope == "workspace_id" else 2])
        + uuid.UUID(dataset[scope]).bytes + uuid.UUID(dataset[lineage]).bytes
        + uuid.UUID(dataset["logical_replica_id"]).bytes + nonce_c + nonce_w
        + hashlib.sha256(credential.encode()).digest())
    assert len(transcript) == 244
    messages = [dict(kind="client_hello", version=1, dataset=dataset, client_nonce=b64(nonce_c), credential=credential),
        dict(kind="worker_challenge", version=1, server_nonce=b64(nonce_w)),
        dict(kind="client_finish", version=1, signature=b64(keys["device"].sign(transcript))),
        dict(kind="session_accepted", version=1, session_id=b64(bytes([32])*32), generation=1, expires_at_seconds=1800000600)]
    sessions.append(dict(dataset=dataset, assignment=assignment,
        transcript_hex=transcript.hex(), transcript_length=244,
        wrong_endpoint_key_signature=b64(keys["client_endpoint"].sign(transcript)),
        messages=[dict(json=encode(message).decode(), frame_hex=(len(encode(message)).to_bytes(4,"big")+encode(message)).hex()) for message in messages]))

negative_tokens = []
for field, value, code in [("aud", "koru-api", "wrong_audience"), ("region", "EU", "wrong_region"),
        ("purpose", "other", "wrong_purpose"), ("iss", "https://other.invalid", "wrong_issuer"),
        ("ver", 2, "credential_version_unsupported"), ("exp", 1800000901, "credential_claims_invalid")]:
    changed = dict(credential_claims)
    changed[field] = value
    negative_tokens.append(dict(id="credential_"+field, token=token(changed,"koru-sync-credential+jwt"), code=code))
combined = dict(credential_claims, region="EU", iss="https://eu.example.invalid")
negative_tokens.append(dict(id="credential_region_and_issuer", token=token(combined,"koru-sync-credential+jwt"), code="wrong_region"))

print(json.dumps(dict(format="cloud-sync-admission-v1-foundation", partial=True,
    gated=["D199 transfer digest carrier", "Plan13 issuance/partial-route response", "platform adapter and live worker evidence"],
    keys={name:dict(secret_hex=(bytes([i])*32).hex(), public_bytes=public[name]) for name,i in [("regional",1),("previous",2),("device",3),("worker",4),("client_endpoint",5)]},
    credential_claims=credential_claims, credential=credential,
    previous_key_credential=token(credential_claims,"koru-sync-credential+jwt","previous"),
    sessions=sessions, negative_tokens=negative_tokens,
    provenance=[dict(json='{"kind":"store"}', result="store"),
        dict(json='{"kind":"cloud","logical_replica_id":'+json.dumps(list(uuid.UUID(identifier(12)).bytes),separators=(",",":"))+'}', result="cloud"),
        dict(json='{"kind":"future"}', result="corrupt"), dict(json='null', result="corrupt"),
        dict(json='{', result="corrupt"), dict(sql_null=True, result="legacy_from_client_or_store_without_rewrite")],
    mapping={"workspace":["workspace_incarnation_id","incarnation_id","sync.cloud_replicas.lineage_id"],
             "profile":["profile_lineage_id","lineage_id","sync.cloud_replicas.lineage_id"]},
    version_gate=dict(workspace_before=11,workspace_after=12,control_before=5,control_after=6,control_frame=1,peer=5)),indent=2))
