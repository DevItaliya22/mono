//! **The trust root: one pinned model-signing key, and what happens when a
//! signature does not come from it.**
//!
//! [ADR-250](../../../docs/decisions/ADR-226-250.md) settles why this exists at
//! all. The short version: a SHA-256 delivered by the same unauthenticated
//! catalog as the URL proves nothing, because whoever can serve a bad model can
//! serve its matching digest. TLS authenticates a host for the length of a
//! connection; it says nothing about an artefact that was signed once and then
//! travelled through a mirror, a proxy, a CDN edge or a corporate cache.
//!
//! ## Three things about this key that are not guessable
//!
//! **It is not the release key**, and the difference is not fastidiousness.
//! Models outlive releases, may one day be signed by whoever publishes the
//! weights, and are served to every channel at once. Sharing the release key
//! would couple two rotation schedules that have nothing to do with each other,
//! and would make one compromise cost both.
//!
//! **It is pinned in source, not in an `option_env!`.** The release key is
//! stamped at compile time from `KORU_UPDATE_PUBLIC_KEY` and is therefore
//! *absent* from a local `cargo` build — which is fine for a build that will
//! never update itself, and not fine here, because the model cache is
//! channel-independent and shared by every build on the machine. A dev build
//! that could not verify would either be unable to install a model or would be
//! tempted into a digest-only path, and the second is how the whole argument
//! above gets quietly undone.
//!
//! **Rotation is additive.** A second key is added beside the first, both
//! verify for as long as both are listed, and the retired one is deleted in a
//! later release. There is no key-fetch endpoint and never will be: a trust
//! root the network can move is not a trust root. Anything already installed is
//! unaffected — verification happened once, at install, against the key that
//! was pinned then, and the signed descriptor persisted beside the bytes is the
//! record of it.
//!
//! ## Why an unknown key and a bad signature are different codes
//!
//! Minisign compares key ids *before* it looks at any bytes, so the two are
//! genuinely distinguishable and the distinction is the one a person needs:
//! [`SignatureUnknownKey`](crate::ModelErrorCode::SignatureUnknownKey) means
//! *you are probably running an old build*, and
//! [`SignatureInvalid`](crate::ModelErrorCode::SignatureInvalid) means
//! *somebody changed something*. One code covering both would send every
//! rotation to a security triage.

use crate::descriptor::{ModelDescriptor, ModelSignature};
use crate::error::{ModelError, ModelErrorCode};
use minisign_verify::{Error as MinisignError, PublicKey, Signature};
use std::sync::OnceLock;

/// **The public keys this build trusts to sign a model.**
///
/// One key for all models — not a key per model — so that what a person trusts
/// is a publisher rather than a catalog row.
///
/// **It is empty, and that is now a decision with a date on it.** The key pair
/// has to be generated by somebody who can hold the private half where the
/// release key lives and rotate it on its own schedule — an operations
/// decision rather than something an implementation plan may take — and the
/// product owner has deferred it past the MVP and before public release.
///
/// Under [`TrustPolicy::SIGNED`], which is the default and the only policy a
/// stable build may use, every install is therefore refused with
/// [`ModelErrorCode::NoTrustRoot`]. That is the correct behaviour for a build
/// that cannot verify anything.
///
/// The MVP needs a path that works, so there is a second, named, guarded
/// policy — [`TrustPolicy::digest_only`] — rather than the thing ADR-250
/// refuses, which was a *silent* digest-only fallback nobody could see. The
/// difference between the two is the whole point: this one is chosen once, is
/// impossible to reach on a stable build, and logs unconditionally when it is
/// used.
///
/// **Nothing is blocked by the absence.** Every verification path in this crate
/// is proven against a *generated* key pair in `crate::fixtures`, so publishing
/// the real public half here is a one-line change and not a piece of work.
/// `docs/features/voice/archive/QUESTIONS.md` Q-V14 and Q-V28 are where that is recorded.
///
/// Each entry may be a bare base64 key or a whole `minisign.pub` block; both
/// are accepted because both are what a person has to hand when adding one.
pub const MODEL_SIGNING_KEYS: &[&str] = &[];

/// The channel this crate was **compiled** for, or `None` for a local build.
///
/// Read here rather than borrowed from `koru_channel::segment()`, and that is
/// the one place this crate is allowed to know anything about a channel. It
/// still does not know *which* channel it is in any way it could act on — it
/// derives no path from this, and the cache stays channel-independent (Q-V26).
/// It knows one thing: whether it is `stable`.
///
/// `option_env!` is evaluated when **this crate** compiles, and `koru-release`
/// builds every package in one `cargo` invocation under one environment for
/// exactly this reason (see `run_cargo`'s note) — so a released stable build
/// carries `Some("stable")` here with no cooperation from any caller.
const RELEASE_CHANNEL: Option<&str> = option_env!("KORU_RELEASE_CHANNEL");

/// The channel name a public release carries.
const STABLE: &str = "stable";

/// **How much a model has to prove before its bytes are installed.**
///
/// Two policies, named once and visibly, rather than a boolean threaded
/// through call sites — and an opaque struct rather than a `pub enum`, so that
/// [`TrustPolicy::DIGEST_ONLY`] cannot be *spelled* outside this module.
/// Reaching it goes through [`TrustPolicy::digest_only`], which is where the
/// guard is; a public variant would put the guard at every call site, which is
/// the same as not having one.
///
/// ## Why the second policy exists at all
///
/// [`MODEL_SIGNING_KEYS`] is empty and is staying empty for the MVP: minting
/// the key, holding the private half offline and publishing the public one is
/// an operations decision the product owner has deferred until before public
/// release. With only [`TrustPolicy::SIGNED`], **every** install refuses
/// `no_trust_root` — which is correct, and which also makes the whole consent
/// and download path unbuildable and untestable. So there is a second policy,
/// and it is loud, guarded, and written down rather than being a `#[cfg]`
/// somebody could flip.
///
/// ## The guard, and why this one
///
/// [`TrustPolicy::digest_only`] is **refused outright on a build compiled for
/// `stable`**, from [`RELEASE_CHANNEL`], which is a compile-time constant of
/// this crate.
///
/// A run-time check against a channel a caller passed in was the obvious
/// alternative and is weaker in the way that matters: it is only as good as
/// what the caller says, and the callers are two different binaries in two
/// different crates. This one cannot be lied to. It also cannot be *forgotten*
/// — there is no call site to remember to add it at — which is the failure
/// mode the whole design is defending against, because the thing being
/// defended against is not an attacker but a release nobody re-read.
///
/// Its known cost, stated rather than hidden: a beta or nightly build **can**
/// install an unsigned model, and somebody running one is trusting the catalog
/// host and TLS instead of a signature. That is the MVP's bargain and it is
/// why the log line below is unconditional.
///
/// **Deleting this arm is the definition of done.** When the key is minted,
/// `MODEL_SIGNING_KEYS` gains its entry, `Signed` starts working, this struct
/// loses its second constructor and its `digest_only` branch, and Q-V14 and
/// Q-V28 are closed. Nothing else has to change: the policy is a value chosen
/// once, at the one place a store is built.
#[derive(Copy, Clone, PartialEq, Eq, Debug, Default)]
pub struct TrustPolicy(Trust);

#[derive(Copy, Clone, PartialEq, Eq, Debug, Default)]
enum Trust {
    #[default]
    Signed,
    DigestOnly,
}

impl TrustPolicy {
    /// **The default, and the only policy a public release may use.** Every
    /// model is verified against a pinned key before a byte is fetched.
    pub const SIGNED: TrustPolicy = TrustPolicy(Trust::Signed);

    /// **The MVP arm.** The signature is not checked; the signed `size` and
    /// `digest` still are, and so is every field rule the descriptor declares.
    ///
    /// Refused on a build compiled for `stable` — see the type's note for why
    /// that guard and not another. The error is
    /// [`ModelErrorCode::NoTrustRoot`], which is the same code the caller
    /// would have met one step later anyway.
    pub fn digest_only() -> Result<TrustPolicy, ModelError> {
        TrustPolicy::digest_only_on(RELEASE_CHANNEL)
    }

    /// The rule with the channel passed in, so both answers are testable in one
    /// build — `digest_only()` can only ever exercise the channel this crate
    /// happened to be compiled for.
    pub fn digest_only_on(channel: Option<&str>) -> Result<TrustPolicy, ModelError> {
        if channel == Some(STABLE) {
            return Err(ModelErrorCode::NoTrustRoot.with(
                "a stable build never installs a model without a signature; \
                 mint the model-signing key and publish its public half",
            ));
        }
        Ok(TrustPolicy(Trust::DigestOnly))
    }

    /// Whether this policy skips the signature. Read by
    /// [`crate::DiskModelStore::install`] and by nothing else.
    pub fn is_digest_only(self) -> bool {
        self.0 == Trust::DigestOnly
    }
}

/// A set of public keys a signature may come from.
///
/// A *value*, not a global, which is what makes this crate testable without a
/// network and without the real key: [`TrustedKeys::pinned`] is the shipped set
/// and every test builds its own from a generated key pair. A hard-coded
/// constant reached directly from the verifier would have made every signature
/// test a test of the shipped key.
#[derive(Clone, Debug)]
pub struct TrustedKeys {
    keys: Vec<PublicKey>,
}

impl TrustedKeys {
    /// The keys this build pins. Parsed once; a malformed entry is a bug in
    /// this file rather than in anything a network said, so it is dropped with
    /// the rest of the set rather than panicking a window at startup — the
    /// resulting empty set refuses installs and says why.
    pub fn pinned() -> &'static TrustedKeys {
        static PINNED: OnceLock<TrustedKeys> = OnceLock::new();
        PINNED.get_or_init(|| {
            TrustedKeys::from_public_keys(MODEL_SIGNING_KEYS)
                .unwrap_or_else(|_| TrustedKeys { keys: Vec::new() })
        })
    }

    /// Build a set from Minisign public keys, each either a bare base64 key or
    /// a whole `minisign.pub` block.
    pub fn from_public_keys<S: AsRef<str>>(keys: &[S]) -> Result<TrustedKeys, ModelError> {
        let mut parsed = Vec::with_capacity(keys.len());
        for key in keys {
            let text = key.as_ref().trim();
            let decoded = PublicKey::decode(text).or_else(|_| PublicKey::from_base64(text));
            parsed.push(decoded.map_err(|e| {
                ModelErrorCode::NoTrustRoot
                    .with(format!("a pinned model-signing key is invalid: {e}"))
            })?);
        }
        Ok(TrustedKeys { keys: parsed })
    }

    /// How many keys are trusted. Zero is a real state — see
    /// [`MODEL_SIGNING_KEYS`] — and a caller that wants to explain itself
    /// before starting a 650 MB download should ask.
    pub fn len(&self) -> usize {
        self.keys.len()
    }

    pub fn is_empty(&self) -> bool {
        self.keys.is_empty()
    }

    /// **Verify a signature over a descriptor's canonical bytes.**
    ///
    /// The order is deliberate and each step has its own code:
    ///
    /// 1. the descriptor's own rules, so an unknown `schema_version` is
    ///    [`SchemaUnsupported`](ModelErrorCode::SchemaUnsupported) rather than
    ///    a forged-looking signature failure;
    /// 2. the trust root exists, so a build with no key says
    ///    [`NoTrustRoot`](ModelErrorCode::NoTrustRoot) rather than accusing the
    ///    catalog;
    /// 3. the signature decodes;
    /// 4. some pinned key made it —
    ///    [`SignatureUnknownKey`](ModelErrorCode::SignatureUnknownKey) when no
    ///    key id matches;
    /// 5. it verifies over *these* bytes —
    ///    [`SignatureInvalid`](ModelErrorCode::SignatureInvalid) otherwise.
    ///
    /// Step 5 is what catches a real signature lifted from another entry: the
    /// bytes it was made over named a different digest, so it does not verify
    /// over these.
    pub fn verify(
        &self,
        descriptor: &ModelDescriptor,
        signature: &ModelSignature,
    ) -> Result<(), ModelError> {
        descriptor.validate()?;
        if self.keys.is_empty() {
            return Err(ModelErrorCode::NoTrustRoot
                .with("this build pins no model-signing key, so nothing can be verified"));
        }
        let bytes = descriptor.canonical_bytes()?;
        let decoded = Signature::decode(signature.as_str()).map_err(|e| {
            ModelErrorCode::SignatureMalformed.with(format!("signature does not decode: {e}"))
        })?;

        // `verify` answers `UnexpectedKeyId` before it hashes anything, so
        // "nobody we trust made this" and "somebody we trust made it and it
        // does not match" are separable — which is the whole reason there are
        // two codes.
        let mut a_pinned_key_made_it = false;
        for key in &self.keys {
            match key.verify(&bytes, &decoded, false) {
                Ok(()) => return Ok(()),
                Err(MinisignError::UnexpectedKeyId) => continue,
                Err(_) => a_pinned_key_made_it = true,
            }
        }
        if a_pinned_key_made_it {
            Err(ModelErrorCode::SignatureInvalid.with(format!(
                "the signature does not verify over the descriptor for {}/{}",
                descriptor.id, descriptor.version
            )))
        } else {
            Err(ModelErrorCode::SignatureUnknownKey.with(format!(
                "the signature for {}/{} names a key this build does not pin",
                descriptor.id, descriptor.version
            )))
        }
    }
}

