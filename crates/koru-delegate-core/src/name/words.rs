//! The two word lists a run's name is drawn from.
//!
//! **Chosen so that every pair is harmless.** A name is generated, nobody
//! approves it, and it appears beside a person's work — so the vocabulary is
//! narrowed to colors, materials, weather, plants, landforms and animals,
//! and nothing that carries a judgement about a person, a body, a group or a
//! run. There is no word here that becomes an insult, a slur or a joke when
//! it lands next to another one: *sunny-otter* and *dusky-quarry* are the
//! shape of the whole space.
//!
//! **Both lists are sorted and strictly ascending**, which is how uniqueness
//! is enforced: `src/tests/name.rs` asserts the order, so a duplicate added
//! later is a failing test rather than a silently doubled probability.
//! Everything is ASCII and lower case, because the name is drawn in eight
//! locales and is a label rather than a translated word.

