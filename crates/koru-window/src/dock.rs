//! The Dock icon, on the platform whose Dock ignores winit's.

/// Put the Koru logo on the Dock icon and in ⌘-Tab.
///
/// **macOS ignores `WindowAttributes::with_window_icon` completely.** A window
/// there has no icon of its own; the picture the Dock and the app switcher show
/// belongs to the *application*, and normally comes from the `.icns` inside an
/// `.app` bundle. A *released* Koru is bundled and carries its `.icns`; a
/// development build run straight out of `target/` is a bare binary, which
/// inherits the generic executable placeholder — the black `exec` tile — and
/// none of the Windows work on `koru.ico` shows up at all.
///
/// Setting `applicationIconImage` gives the running process the right picture
/// without a bundle, and keeps working inside one — a bundle's `.icns` is the
/// default, and this overrides it with the same artwork.
///
/// Lives here rather than in `koru-workspace-host` because two binaries now show in
/// the Dock — the shell and the agent (whose overlay window puts it there) —
/// and the agent may not link the shell. Same argument as
/// [`crate::activate_app`]. Compiled in rather than read from `assets/`: an
/// icon that depends on a path is an icon that goes missing. AppKit does its
/// own downscaling to every size the Dock wants. Must be called on the main
/// thread; anywhere else it quietly does nothing.
///
/// **`logo-dock.png`, not `logo.png`.** Apple's icon grid puts the artwork on
/// an 824-wide tile inside a 1024 canvas, and every neighbouring Dock icon
/// carries that margin baked in — the full-bleed logo read as *larger* than
/// the apps beside it. The derivative is generated by `scripts/icons/set-logo.py`
/// (`./koru.sh logo`), so a new logo regenerates it.
#[cfg(target_os = "macos")]
pub fn set_dock_icon() {
    use objc2::AnyThread;
    use objc2_app_kit::{NSApplication, NSImage};
    use objc2_foundation::{MainThreadMarker, NSData};

    let Some(mtm) = MainThreadMarker::new() else {
        return;
    };
    // The channel tint has to land before AppKit sees the bytes, so a
    // non-stable build decodes, tints and re-encodes the PNG in memory;
    // stable hands the embedded bytes over untouched. Same recipe as the
    // window icon and the trays — the run-time half of ADR-139.
    const LOGO: &[u8] = include_bytes!("../../../assets/logo-dock.png");
    let tint = koru_channel::tint::tint();
    let tinted;
    let bytes: &[u8] = if tint == koru_channel::tint::Tint::None {
        LOGO
    } else {
        match tinted_png(LOGO, tint) {
            Some(png) => {
                tinted = png;
                &tinted
            }
            None => LOGO,
        }
    };
    let data = NSData::with_bytes(bytes);
    let Some(image) = NSImage::initWithData(NSImage::alloc(), &data) else {
        return;
    };
    // SAFETY: setting the application's icon from a decoded image on the main
    // thread, which `MainThreadMarker` proves we are on. objc2 marks it unsafe
    // because AppKit setters are; there is no invariant to uphold beyond that.
    unsafe {
        NSApplication::sharedApplication(mtm).setApplicationIconImage(Some(&image));
    }
}

/// Decode a PNG, tint it, and encode it back — the dock takes bytes, not RGBA.
#[cfg(target_os = "macos")]
fn tinted_png(png: &[u8], tint: koru_channel::tint::Tint) -> Option<Vec<u8>> {
    let rgba = image::load_from_memory(png).ok()?.to_rgba8();
    let (width, height) = rgba.dimensions();
    let mut pixels = rgba.into_raw();
    koru_channel::tint::apply(&mut pixels, tint);
    let mut out = std::io::Cursor::new(Vec::new());
    image::write_buffer_with_format(
        &mut out,
        &pixels,
        width,
        height,
        image::ExtendedColorType::Rgba8,
        image::ImageFormat::Png,
    )
    .ok()?;
    Some(out.into_inner())
}

#[cfg(not(target_os = "macos"))]
pub fn set_dock_icon() {}
